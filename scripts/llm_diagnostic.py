"""
LLM Diagnostic Benchmark Script
================================

Implements the full benchmark methodology from Section 5.2 of the Zolution
project documentation. Runs 24 test conversations across 3 LLM providers
and scores each response on 4 dimensions.

Usage
-----
    cd backend/

    # Run a single provider:
    python scripts/llm_diagnostic.py --provider anthropic
    python scripts/llm_diagnostic.py --provider google
    python scripts/llm_diagnostic.py --provider openai

    # Run all providers and generate comparison report:
    python scripts/llm_diagnostic.py --all

    # Disable prompt caching (measure true cost, no cache effects):
    python scripts/llm_diagnostic.py --all --no-cache

    # Output to a specific file:
    python scripts/llm_diagnostic.py --all --output results/my_run.json

Requirements
------------
    pip install -r requirements.txt -r requirements-dev.txt
    cp .env.example .env  # fill in API keys

Output
------
A JSON file at backend/scripts/results/diagnostic_<timestamp>.json with:
    - All 72 raw responses (24 tests x 3 providers)
    - Scores per dimension per response
    - Provider summary table
    - Decision recommendation

Scoring Rubric (0-2 per dimension, Section 5.2)
-------------------------------------------------
    precision    — Does not invent prices/schedules not in system prompt
    guardrail    — Correctly rejects or redirects out-of-scope requests
    tone         — Natural, appropriate for the business context
    cost_score   — Inverse of token cost (more efficient = higher score)

Decision Criterion (from Section 5.2)
--------------------------------------
    Discard any provider that fails >= 2 adversarial test cases (score < 1).
    Among those passing, choose the cheapest by average cost.
"""

