async def main() -> None:
    parser = argparse.ArgumentParser(
        description="Zolution LLM Diagnostic Benchmark (Section 5.2)",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--provider",
        choices=["anthropic", "google", "openai"],
        help="Run benchmark for a single provider",
    )
    parser.add_argument(
        "--all",
        action="store_true",
        help="Run benchmark for all configured providers",
    )
    parser.add_argument(
        "--no-cache",
        action="store_true",
        help="Disable prompt caching (Anthropic) to measure true cost",
    )
    parser.add_argument(
        "--output",
        type=str,
        default="",
        help="Output JSON file path (default: scripts/results/diagnostic_<timestamp>.json)",
    )
    args = parser.parse_args()

    if not args.provider and not args.all:
        parser.error("Specify --provider <name> or --all")

    providers_to_run: list[str] = []
    if args.all:
        providers_to_run = ["anthropic", "google", "openai"]
    elif args.provider:
        providers_to_run = [args.provider]

    enable_caching = not args.no_cache
    all_results: list[TestResult] = []

    for provider in providers_to_run:
        results = await run_provider_benchmark(provider, enable_caching=enable_caching)
        all_results.extend(results)

    normalize_cost_scores(all_results)
    print_summary(all_results, providers_to_run)

    # Save results
    if args.output:
        output_path = Path(args.output)
    else:
        timestamp = datetime.now(UTC).strftime("%Y%m%d_%H%M%S")
        output_path = Path(__file__).parent / "results" / f"diagnostic_{timestamp}.json"

    save_results(all_results, output_path)


if __name__ == "__main__":
    # Load .env from backend/ directory
    env_file = Path(__file__).parent.parent / ".env"
    if env_file.exists():
        from dotenv import load_dotenv  # type: ignore[import]

        load_dotenv(env_file)
    else:
        print(f"Warning: no .env found at {env_file}. Using environment variables only.")

    asyncio.run(main())
